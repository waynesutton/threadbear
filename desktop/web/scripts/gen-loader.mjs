#!/usr/bin/env node
// Writes desktop/web/src/mac/loader.rs: every function in CEF's C API, as a
// forwarder to the framework the app loads at run time from its data folder.
//
// Why: cef-dll-sys's build script downloads CEF (135 MB) and builds its C++
// wrapper with cmake and ninja on every machine that builds the app. All
// that wrapper does on a Mac is this (libcef_dll_dylib.cc: each function
// looked up in the framework once it's loaded). So desktop/web turns the
// build script off (cef-dll-sys's `dox` feature) and supplies the functions
// itself, from cef-dll-sys's own generated declarations, so the types are
// exactly the ones the `cef` crate calls them with.
//
//   node desktop/web/scripts/gen-loader.mjs \
//     <cargo registry>/cef-dll-sys-156.3.0+156.0.15/src/bindings/aarch64_apple_darwin.rs \
//     > desktop/web/src/mac/loader.rs
//
// Run it again when the cef pin in desktop/web/Cargo.toml moves (the two Mac
// bindings files are the same). The file ends in a check the compiler makes:
// each forwarder's type against cef-dll-sys's own declaration of it, so one
// that doesn't match the bindings doesn't build.
import fs from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('usage: gen-loader.mjs <cef-dll-sys bindings .rs>');
  process.exit(2);
}
const text = fs.readFileSync(file, 'utf8');

// The text between `open` and the bracket that closes it.
function balanced(s, start, open, close) {
  let depth = 0;
  for (let i = start; i < s.length; i++) {
    if (s[i] === open) depth++;
    else if (s[i] === close) {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error(`unbalanced ${open}${close} at ${start}`);
}

// Splits "a: T, b: Option<fn(x, y)>" at the commas that aren't nested.
function topLevelSplit(s) {
  const out = [];
  let depth = 0, cur = '';
  for (const ch of s) {
    if ('(<['.includes(ch)) depth++;
    if (')>]'.includes(ch)) depth--;
    if (ch === ',' && depth === 0) {
      out.push(cur);
      cur = '';
    } else cur += ch;
  }
  if (cur.trim()) out.push(cur);
  return out.map((a) => a.trim()).filter(Boolean);
}

const fns = [];
const re = /pub fn (cef_[a-z0-9_]+)\(/g;
let m;
while ((m = re.exec(text))) {
  const name = m[1];
  const openAt = m.index + m[0].length - 1;
  const closeAt = balanced(text, openAt, '(', ')');
  const args = topLevelSplit(text.slice(openAt + 1, closeAt)).map((a) => {
    const colon = a.indexOf(':');
    return { name: a.slice(0, colon).trim(), type: a.slice(colon + 1).trim().replace(/\s+/g, ' ') };
  });
  const semi = text.indexOf(';', closeAt);
  const tail = text.slice(closeAt + 1, semi).trim();
  const ret = tail.startsWith('->') ? tail.slice(2).trim().replace(/\s+/g, ' ') : null;
  if (args.some((a) => a.name === '...' || a.type.includes('...'))) throw new Error(`${name} is variadic`);
  fns.push({ name, args, ret });
}
if (fns.length < 150) throw new Error(`only ${fns.length} functions found: is ${file} cef-dll-sys's bindings?`);

// Written by hand in loader_support.rs: the loader itself, which is the
// wrapper's own code rather than the framework's.
const own = new Set(['cef_load_library', 'cef_unload_library', 'cef_scoped_library_loader_create', 'cef_scoped_library_loader_free']);

const out = [];
out.push(`// Generated by desktop/web/scripts/gen-loader.mjs from cef-dll-sys's
// bindings (see there for why). Don't edit by hand: run it again.
//
// Each function looks itself up in the framework the first time it's called
// (loader_support.rs) and calls through. ${fns.length} functions; the four the wrapper
// itself provides (cef_load_library and friends) are in loader_support.rs.
#![allow(clippy::missing_safety_doc, clippy::too_many_arguments, non_snake_case)]
use super::loader_support::Slot;
use cef_dll_sys::*;
`);
for (const f of fns) {
  if (own.has(f.name)) continue;
  const params = f.args.map((a) => `${a.name}: ${a.type}`).join(', ');
  const types = f.args.map((a) => a.type).join(', ');
  const names = f.args.map((a) => a.name).join(', ');
  const ret = f.ret ? ` -> ${f.ret}` : '';
  out.push(`#[no_mangle]
pub unsafe extern "C" fn ${f.name}(${params})${ret} {
    static SLOT: Slot = Slot::new(c"${f.name}");
    let f = unsafe { std::mem::transmute::<*mut std::ffi::c_void, unsafe extern "C" fn(${types})${ret}>(SLOT.get()) };
    unsafe { f(${names}) }
}
`);
}
// Each pair has to be one type to share an array: this file's function and
// cef-dll-sys's declaration of the same one (which the linker resolves to
// this file's, so naming it costs nothing).
const checks = fns.map((f) => {
  const holes = f.args.map(() => '_').join(', ');
  const path = own.has(f.name) ? `super::loader_support::${f.name}` : f.name;
  return `    let _ = [${path} as unsafe extern "C" fn(${holes})${f.ret ? ' -> _' : ''}, cef_dll_sys::${f.name}];`;
});
out.push(`/// Never called: it only has to compile (see the top of gen-loader.mjs).
#[allow(dead_code)]
fn signatures_match_the_bindings() {
${checks.join('\n')}
}
`);
process.stdout.write(out.join('\n'));
